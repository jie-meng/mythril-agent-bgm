def test_generate_extension_contains_expected_pieces():
    ext = PiIntegration._generate_extension("/x/bgm")
    # Header comment: auto-generated marker (canonical repo URL) + hint.
    assert "Auto-generated by AI BGM" in ext
    assert "https://github.com/jie-meng/mythril-agent-bgm" in ext
    assert "Re-run `bgm setup` to regenerate." in ext
    # Plain-JS-compatible ESM: no TS type annotations, types via JSDoc only.
    assert 'import { spawn } from "node:child_process";' in ext
    assert 'const BGM = "/x/bgm";' in ext
    assert "export default function (pi)" in ext
    assert '@param {import("@earendil-works/pi-coding-agent").ExtensionAPI} pi' in ext
    # The five event handlers.
    assert 'pi.on("agent_start"' in ext
    assert 'pi.on("agent_end"' in ext
    assert 'pi.on("tool_call"' in ext
    assert 'pi.on("tool_result"' in ext
    assert 'pi.on("session_shutdown"' in ext
    # BGM commands.
    assert 'run("play", "work", "0")' in ext
    assert 'run("play", "done")' in ext
    assert 'run("play", "notification", "0")' in ext
    assert 'run("stop")' in ext
    # spawn configuration: detached + windowsHide, errors swallowed.
    assert 'stdio: "ignore"' in ext
    assert "detached: true" in ext
    assert "windowsHide: true" in ext
    assert 'child.on("error", () => {})' in ext
    assert "child.unref()" in ext
    # Work/done gating and question bookkeeping.
    assert "let lastWorkTime = 0;" in ext
    assert "const pendingQuestions = new Set();" in ext
    assert "lastWorkTime > 0" in ext
    assert "pendingQuestions.add(event.toolCallId)" in ext
    assert "pendingQuestions.delete(event.toolCallId)" in ext
    assert "pendingQuestions.clear()" in ext
    # Conservative question/ask tool-name matching. Optional chaining guards
    # against a missing toolName: an undefined field must never throw a
    # TypeError into the pi process.
    assert 'event.toolName === "question"' in ext
    assert 'event.toolName?.startsWith("ask")' in ext
    assert 'event.toolName.startsWith("ask")' not in ext


def test_generate_extension_event_mapping():
    ext = PiIntegration._generate_extension("/x/bgm")
    # agent_start drives work and records the timestamp.
    start_block = ext[ext.index('pi.on("agent_start"') : ext.index('pi.on("agent_end"')]
    assert "lastWorkTime = Date.now()" in start_block
    assert 'run("play", "work", "0")' in start_block
    # agent_end gates the done cue on work music having actually played.
    end_block = ext[ext.index('pi.on("agent_end"') : ext.index('pi.on("tool_call"')]
    assert "lastWorkTime > 0" in end_block
    assert 'run("play", "done")' in end_block
    assert 'run("play", "work", "0")' not in end_block
    # tool_call -> notification, pendingQuestions add, work marker reset.
    call_block = ext[ext.index('pi.on("tool_call"') : ext.index('pi.on("tool_result"')]
    assert "pendingQuestions.add(event.toolCallId)" in call_block
    assert "lastWorkTime = 0" in call_block
    assert 'run("play", "notification", "0")' in call_block
    # tool_result -> resume work only when the callId was pending.
    result_block = ext[ext.index('pi.on("tool_result"') : ext.index('pi.on("session_shutdown"')]
    assert "pendingQuestions.delete(event.toolCallId)" in result_block
    assert "lastWorkTime = Date.now()" in result_block
    assert 'run("play", "work", "0")' in result_block
    # session_shutdown clears bookkeeping first, then stops the music.
    shutdown_block = ext[ext.index('pi.on("session_shutdown"') :]
    assert "pendingQuestions.clear()" in shutdown_block
    assert "lastWorkTime = 0" in shutdown_block
    assert 'run("stop")' in shutdown_block


