def test_generated_extension_passes_node_syntax_check(tmp_path: Path):
    # The generated extension must be plain-JS-compatible ESM so pi's jiti
    # loader accepts it; `node --check` verifies the syntax exactly as it
    # would be loaded from ~/.pi/agent/extensions/. Skipped when node is not
    # available on this machine.
    node = shutil.which("node")
    if node is None:
        pytest.skip("node not available on this machine — skipping syntax check")
    extension = tmp_path / "mythril-agent-bgm.ts"
    extension.write_text(PiIntegration._generate_extension("/x/bgm"), encoding="utf-8")
    result = subprocess.run(
        [node, "--check", str(extension)],
        capture_output=True,
        text=True,
    )
    assert result.returncode == 0, result.stderr


def test_setup_cleanup_roundtrip(fake_home: Path, patched_home):
    fake_bgm = _make_bgm(fake_home)
    with patched_home:
        with mock.patch("shutil.which", return_value=str(fake_bgm)):
            integration = PiIntegration()
            assert not integration.is_configured()

            ok, _ = integration.perform_setup()
            assert ok
            assert integration.is_configured()
            assert integration.is_up_to_date()
            assert integration.get_settings_path().exists()

            ok, _ = integration.perform_cleanup()
            assert ok
            assert not integration.is_configured()
            assert not integration.get_settings_path().exists()


def test_setup_cleanup_idempotent(fake_home: Path, patched_home):
    fake_bgm = _make_bgm(fake_home)
    with patched_home:
        with mock.patch("shutil.which", return_value=str(fake_bgm)):
            integration = PiIntegration()
            ok, _ = integration.perform_setup()
            assert ok
            extension = integration.get_settings_path()
            first = extension.read_text(encoding="utf-8")
            assert not list(extension.parent.glob("mythril-agent-bgm.ts.*.bak"))

            # Repeated setup with identical content: no rewrite, no backup.
            ok, _ = integration.perform_setup()
            assert ok
            assert extension.read_text(encoding="utf-8") == first
            assert not list(extension.parent.glob("mythril-agent-bgm.ts.*.bak"))

            ok, _ = integration.perform_cleanup()
            assert ok
            assert not extension.exists()
            # Repeated cleanup: file already gone, still a success.
            ok, message = integration.perform_cleanup()
            assert ok
            assert "nothing to clean up" in message


def test_cleanup_removes_only_own_file(fake_home: Path, patched_home):
    fake_bgm = _make_bgm(fake_home)
    ext_dir = fake_home / ".pi" / "agent" / "extensions"
    ext_dir.mkdir(parents=True)
    other = ext_dir / "other-extension.ts"
    other.write_text("export default function (pi) {}\n", encoding="utf-8")
    with patched_home:
        with mock.patch("shutil.which", return_value=str(fake_bgm)):
            integration = PiIntegration()
            ok, _ = integration.perform_setup()
            assert ok
            ok, _ = integration.perform_cleanup()
            assert ok
            # Must be checked inside the patched home — outside it, this reads
            # the developer's real ~/.pi extension and fails on any machine
            # where bgm is actually hooked into pi.
            assert not integration.get_settings_path().exists()
    assert other.exists()
    assert other.read_text(encoding="utf-8") == "export default function (pi) {}\n"


def test_cleanup_unlinks_symlink(fake_home: Path, patched_home):
    # A symlinked extension must be unlinked (rmtree on a symlink raises
    # OSError) and the target must be left untouched.
    target = fake_home / "real-extension.ts"
    target.write_text("export default function (pi) {}\n", encoding="utf-8")
    ext_dir = fake_home / ".pi" / "agent" / "extensions"
    ext_dir.mkdir(parents=True)
    link = ext_dir / "mythril-agent-bgm.ts"
    try:
        link.symlink_to(target)
    except OSError:
        pytest.skip("symlinks not supported on this platform")
    with patched_home:
        ok, _ = PiIntegration().perform_cleanup()
        assert ok
    assert not link.exists()
    assert target.exists()


