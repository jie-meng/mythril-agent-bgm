def test_setup_backs_up_with_unique_timestamped_names(fake_home: Path, patched_home):
    # Two consecutive setups with different existing content must both succeed
    # and produce DISTINCT backups (a fixed ".bak" name would collide:
    # FileExistsError on Windows, silent overwrite of the previous backup on
    # POSIX — exactly the "bgm path changed, re-run setup" scenario).
    fake_bgm = _make_bgm(fake_home)
    ext_dir = fake_home / ".pi" / "agent" / "extensions"
    ext_dir.mkdir(parents=True)
    extension = ext_dir / "mythril-agent-bgm.ts"
    extension.write_text("// first user version\n", encoding="utf-8")
    with patched_home:
        with mock.patch("shutil.which", return_value=str(fake_bgm)):
            integration = PiIntegration()
            ok, _ = integration.perform_setup()
            assert ok
            generated = extension.read_text(encoding="utf-8")
            # Second setup sees a different existing file again (e.g. a user
            # edit after the first install).
            extension.write_text(generated + "\n// tampered\n", encoding="utf-8")
            ok, _ = integration.perform_setup()
            assert ok
            assert extension.read_text(encoding="utf-8") == generated
    backups = list(ext_dir.glob("mythril-agent-bgm.ts.*.bak"))
    assert len(backups) == 2
    assert len({backup.name for backup in backups}) == 2
    assert {backup.read_text(encoding="utf-8") for backup in backups} == {
        "// first user version\n",
        generated + "\n// tampered\n",
    }


def test_configured_and_up_to_date_combinations(fake_home: Path, patched_home):
    fake_bgm = _make_bgm(fake_home)
    with patched_home:
        with mock.patch("shutil.which", return_value=str(fake_bgm)):
            integration = PiIntegration()
            # (missing): not configured, not up to date.
            assert not integration.is_configured()
            assert not integration.is_up_to_date()

            ok, _ = integration.perform_setup()
            assert ok
            # (exists, matching): configured and up to date.
            assert integration.is_configured()
            assert integration.is_up_to_date()

            # (exists, different): configured but not up to date.
            extension = integration.get_settings_path()
            extension.write_text(
                extension.read_text(encoding="utf-8") + "\n// tampered\n", encoding="utf-8"
            )
            assert integration.is_configured()
            assert not integration.is_up_to_date()

            ok, _ = integration.perform_cleanup()
            assert ok
            # (missing again): not configured, not up to date.
            assert not integration.is_configured()
            assert not integration.is_up_to_date()


def test_up_to_date_false_after_bgm_path_change(fake_home: Path, patched_home):
    fake_bgm = _make_bgm(fake_home)
    other_bgm = fake_home / "other-bgm"
    other_bgm.write_text("#!/bin/sh\necho ok\n", encoding="utf-8")
    other_bgm.chmod(0o755)
    with patched_home:
        with mock.patch("shutil.which", return_value=str(fake_bgm)):
            integration = PiIntegration()
            ok, _ = integration.perform_setup()
            assert ok
            assert integration.is_up_to_date()
        # bgm moved: embedded path no longer matches generated content.
        with mock.patch("shutil.which", return_value=str(other_bgm)):
            assert not integration.is_up_to_date()


